#!/usr/bin/env node
// Builds site/catalog.js (and site/artifact.html) from the marketplace, each SKILL.md's frontmatter,
// and the curated summaries/tags in catalog/skills.json.
// Usage: node scripts/build-catalog.mjs [--check]
//   --check  fail if a skill lacks curated metadata or site/catalog.js is stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const readJSON = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));

const marketplace = readJSON('.claude-plugin/marketplace.json');
const curated = readJSON('catalog/skills.json');
const knownTags = new Set(Object.values(curated.tagGroups).flat());

// Minimal YAML frontmatter reader: top-level `key: value` pairs, quoted or plain.
function frontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return {};
  const out = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!kv) continue;
    let v = kv[2].trim();
    if (v.startsWith('"')) { try { v = JSON.parse(v); } catch { v = v.slice(1, -1); } }
    else if (v.startsWith("'")) v = v.slice(1, -1).replace(/''/g, "'");
    out[kv[1]] = v;
  }
  return out;
}

const errors = [];
const skills = [];
const plugins = [];
for (const p of marketplace.plugins) {
  const dir = path.join(root, p.source);
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, '.claude-plugin/plugin.json'), 'utf8'));
  const commandsDir = path.join(dir, 'commands');
  const commands = fs.existsSync(commandsDir)
    ? fs.readdirSync(commandsDir).filter((f) => f.endsWith('.md')).map((f) => f.replace(/\.md$/, '')).sort()
    : [];
  plugins.push({
    name: p.name,
    description: p.description || manifest.description,
    version: manifest.version || null,
    license: manifest.license || null,
    upstream: manifest.repository || null,
    author: manifest.author?.name || null,
    commands,
    install: `/plugin install ${p.name}@${curated.marketplace}`,
  });
  const skillsDir = path.join(dir, 'skills');
  for (const s of fs.readdirSync(skillsDir).sort()) {
    const file = path.join(skillsDir, s, 'SKILL.md');
    if (!fs.existsSync(file)) continue;
    const fm = frontmatter(fs.readFileSync(file, 'utf8'));
    const name = fm.name || s;
    const meta = curated.skills[name];
    if (!meta) { errors.push(`${name}: no entry in catalog/skills.json`); continue; }
    if (!meta.summary) errors.push(`${name}: missing summary`);
    if (!meta.tags?.length) errors.push(`${name}: missing tags`);
    for (const t of meta.tags || []) if (!knownTags.has(t)) errors.push(`${name}: tag "${t}" is not in any tagGroup`);
    skills.push({
      name,
      plugin: p.name,
      category: meta.category || 'Other',
      summary: meta.summary,
      tags: meta.tags,
      requires: meta.requires || [],
      example: meta.example || null,
      argumentHint: fm['argument-hint'] || null,
      description: fm.description || '',
      path: path.relative(root, file).split(path.sep).join('/'),
    });
  }
}
for (const name of Object.keys(curated.skills)) {
  if (!skills.some((s) => s.name === name)) errors.push(`${name}: in catalog/skills.json but no SKILL.md found`);
}
if (errors.length) { console.error('Catalog errors:\n  ' + errors.join('\n  ')); process.exit(1); }

const usedTags = new Set(skills.flatMap((s) => s.tags));
const tagGroups = Object.fromEntries(
  Object.entries(curated.tagGroups).map(([g, ts]) => [g, ts.filter((t) => usedTags.has(t))]).filter(([, ts]) => ts.length)
);
const catalog = { repo: curated.repo, branch: curated.branch, marketplace: curated.marketplace, artifactUrl: curated.artifactUrl || null, tagGroups, plugins, skills };
const js = `// Generated by scripts/build-catalog.mjs. Edit catalog/skills.json instead.\nwindow.SKILLS_CATALOG = ${JSON.stringify(catalog, null, 2)};\n`;
const outFile = path.join(root, 'site/catalog.js');

// The claude.ai artifact gets the same page without the document wrapper
// (the Artifact tool adds its own <html>/<head>/<body> skeleton).
const page = fs.readFileSync(path.join(root, 'site/index.html'), 'utf8');
const artifactHtml = '<!-- Generated from site/index.html by scripts/build-catalog.mjs. Do not edit. -->\n' + page
  .replace(/<!doctype html>\s*/i, '')
  .replace(/<html[^>]*>\s*/i, '')
  .replace(/<head>\s*/i, '')
  .replace(/<meta charset="utf-8">\s*/i, '')
  .replace(/<meta name="viewport"[^>]*>\s*/i, '')
  .replace(/html \{ padding-top: env\(safe-area-inset-top, 0px\); padding-bottom: env\(safe-area-inset-bottom, 0px\); \}\n/, '')
  .replace(/\s*<\/head>\s*<body>\s*/i, '\n')
  .replace(/\s*<\/body>\s*<\/html>\s*$/i, '\n');
const artifactFile = path.join(root, 'site/artifact.html');

if (check) {
  const read = (f) => (fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '');
  if (read(outFile) !== js || read(artifactFile) !== artifactHtml) { console.error('site/catalog.js or site/artifact.html is out of date. Run: node scripts/build-catalog.mjs'); process.exit(1); }
  console.log(`Catalog OK: ${skills.length} skills in ${plugins.length} plugins.`);
} else {
  fs.writeFileSync(outFile, js);
  fs.writeFileSync(artifactFile, artifactHtml);
  console.log(`Wrote site/catalog.js and site/artifact.html: ${skills.length} skills in ${plugins.length} plugins.`);
}
